import { browser, open, sleep } from "./lib.mjs";
import fs from "fs";
const OUT = process.argv[2];
const b = await browser();
const p = await open(b, "", { draw: true, w: 1280, h: 800 });
await p.waitForFunction(() => roomCode && room);
await p.evaluate(() => { beginGame(); });
await p.waitForFunction(() => running);
await p.evaluate(() => { newGame(1234, 0, 2); running = true; });
await sleep(1500);
const cdp = await p.context().newCDPSession(p);
const shot = async name => { await p.evaluate(() => { readWorld(); renderTopBar(); renderSelection(true); drawMinimap(); }); await sleep(900); const { data } = await cdp.send("Page.captureScreenshot", { format: "png" }); fs.writeFileSync(`${OUT}/${name}.png`, Buffer.from(data, "base64")); };
await p.evaluate(() => { paused = true; W.debug_set_era(2); readWorld(); for (let i = 0; i < entCount; i++) if (E(i, F.owner) === ME && E(i, F.kind) === K.Worker) { setSelection([E(i, F.id)]); return; } });
await shot("p1-page0");
await p.keyboard.press("Tab"); await p.keyboard.press("Tab");
const page = await p.evaluate(() => buildPage);
await shot("p2-page2");
await p.keyboard.press("Shift+Tab");
console.log("pages", page, await p.evaluate(() => buildPage), "errors", p.errors.slice(0, 3));
await b.close();
